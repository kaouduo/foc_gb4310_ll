#include "pwm_output_stm32.h"
#include "bsp_board_config.h"
#include "stm32g4xx_ll_bus.h"

/**
 *  @brief  配置 TIM1 三相主输出和互补输出的 GPIO 复用。
 *  @param  无。
 *  @return 无返回值。
 *  @note   启动阶段且 TIM1 输出关闭时调用；使能 GPIO 时钟并修改六路引脚配置，不启动 PWM；无失败状态返回。
 */
void PWM_Output_BoardIO_Init(void)
{
    LL_AHB2_GRP1_EnableClock(LL_AHB2_GRP1_PERIPH_GPIOA | LL_AHB2_GRP1_PERIPH_GPIOB);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH1_PORT, BSP_BOARD_PWM_CH1_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH1_PORT, BSP_BOARD_PWM_CH1_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH1_PORT, BSP_BOARD_PWM_CH1_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH1_PORT, BSP_BOARD_PWM_CH1_PIN, BSP_BOARD_PWM_CH1_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH1_PORT, BSP_BOARD_PWM_CH1_PIN, LL_GPIO_MODE_ALTERNATE);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH2_PORT, BSP_BOARD_PWM_CH2_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH2_PORT, BSP_BOARD_PWM_CH2_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH2_PORT, BSP_BOARD_PWM_CH2_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH2_PORT, BSP_BOARD_PWM_CH2_PIN, BSP_BOARD_PWM_CH2_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH2_PORT, BSP_BOARD_PWM_CH2_PIN, LL_GPIO_MODE_ALTERNATE);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH3_PORT, BSP_BOARD_PWM_CH3_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH3_PORT, BSP_BOARD_PWM_CH3_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH3_PORT, BSP_BOARD_PWM_CH3_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH3_PORT, BSP_BOARD_PWM_CH3_PIN, BSP_BOARD_PWM_CH3_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH3_PORT, BSP_BOARD_PWM_CH3_PIN, LL_GPIO_MODE_ALTERNATE);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH1N_PORT, BSP_BOARD_PWM_CH1N_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH1N_PORT, BSP_BOARD_PWM_CH1N_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH1N_PORT, BSP_BOARD_PWM_CH1N_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH1N_PORT, BSP_BOARD_PWM_CH1N_PIN, BSP_BOARD_PWM_CH1N_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH1N_PORT, BSP_BOARD_PWM_CH1N_PIN, LL_GPIO_MODE_ALTERNATE);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH2N_PORT, BSP_BOARD_PWM_CH2N_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH2N_PORT, BSP_BOARD_PWM_CH2N_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH2N_PORT, BSP_BOARD_PWM_CH2N_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH2N_PORT, BSP_BOARD_PWM_CH2N_PIN, BSP_BOARD_PWM_CH2N_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH2N_PORT, BSP_BOARD_PWM_CH2N_PIN, LL_GPIO_MODE_ALTERNATE);
    LL_GPIO_SetPinOutputType(BSP_BOARD_PWM_CH3N_PORT, BSP_BOARD_PWM_CH3N_PIN, LL_GPIO_OUTPUT_PUSHPULL);
    LL_GPIO_SetPinSpeed(BSP_BOARD_PWM_CH3N_PORT, BSP_BOARD_PWM_CH3N_PIN, LL_GPIO_SPEED_FREQ_HIGH);
    LL_GPIO_SetPinPull(BSP_BOARD_PWM_CH3N_PORT, BSP_BOARD_PWM_CH3N_PIN, LL_GPIO_PULL_NO);
    LL_GPIO_SetAFPin_8_15(BSP_BOARD_PWM_CH3N_PORT, BSP_BOARD_PWM_CH3N_PIN, BSP_BOARD_PWM_CH3N_AF);
    LL_GPIO_SetPinMode(BSP_BOARD_PWM_CH3N_PORT, BSP_BOARD_PWM_CH3N_PIN, LL_GPIO_MODE_ALTERNATE);
}
